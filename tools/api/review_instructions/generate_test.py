"""Tests assembling the Copilot API review instructions.
"""
import contextlib
import io
import pathlib
import tempfile
import unittest

from tools.api.review_instructions import generate

HEADER = '---\napplyTo: "**"\n---\n\n# Review\n\nScope.\n'


class RenderTest(unittest.TestCase):

    def test_frontmatter_stays_first_and_sources_follow_in_order(self):
        output = generate.render(
            HEADER, [('api/A.md', '# A\n\nAlpha.\n'), ('api/B.md', '\n# B\n\nBeta.\n\n')])
        self.assertTrue(output.startswith('---\napplyTo: "**"\n---\n\n<!-- Generated by '))
        self.assertIn('header.md, api/A.md, api/B.md. Do not edit;', output)
        self.assertTrue(output.endswith('# Review\n\nScope.\n\n# A\n\nAlpha.\n\n# B\n\nBeta.\n'))

    def test_header_without_frontmatter_is_rejected(self):
        with self.assertRaises(ValueError):
            generate.render('# Review\n', [])


class MainTest(unittest.TestCase):

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self._tmp.name)
        paths = generate.repo_paths(self.root)
        for path, content in [(paths.header, HEADER)] + [(source, f'# {source.name}\n')
                                                          for source in paths.sources]:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        paths.output.parent.mkdir(parents=True)
        self.output = paths.output

    def tearDown(self):
        self._tmp.cleanup()

    def run_main(self, mode):
        with contextlib.redirect_stderr(io.StringIO()) as stderr:
            status = generate.main([f'--mode={mode}', f'--root={self.root}'])
        return status, stderr.getvalue()

    def test_check_fails_when_missing_and_fix_writes_it(self):
        status, stderr = self.run_main('check')
        self.assertEqual(1, status)
        self.assertIn('proto_format.sh fix', stderr)
        self.assertFalse(self.output.exists())

        self.assertEqual((0, ''), self.run_main('fix'))
        self.assertEqual(generate.generate(self.root), self.output.read_text())
        self.assertEqual((0, ''), self.run_main('check'))

    def test_check_fails_after_source_edit(self):
        self.run_main('fix')
        (self.root / 'api/STYLE.md').write_text('# Changed\n')
        self.assertEqual(1, self.run_main('check')[0])


if __name__ == '__main__':
    unittest.main()
